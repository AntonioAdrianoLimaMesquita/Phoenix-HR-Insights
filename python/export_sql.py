"""Export data tables and produce SQL Server-compatible warehouse DDL."""
from __future__ import annotations

from pathlib import Path
import json
import pandas as pd


SQL_TYPES = {
    "int64": "INT", "int32": "INT", "float64": "DECIMAL(18,2)", "bool": "BIT",
    "datetime64[ns]": "DATE", "object": "VARCHAR(255)", "string": "VARCHAR(255)",
}


def _sql_type(series: pd.Series) -> str:
    if pd.api.types.is_datetime64_any_dtype(series):
        return "DATE"
    if pd.api.types.is_bool_dtype(series):
        return "BIT"
    if pd.api.types.is_integer_dtype(series):
        return "INT"
    if pd.api.types.is_float_dtype(series):
        return "DECIMAL(18,3)"
    if series.name.endswith("Date") or series.name in {"MonthStart", "MonthEnd", "SnapshotDate", "CompletionDate", "MovementDate", "TerminationDate", "HireDate", "BirthDate"}:
        return "DATE"
    max_len = int(series.astype(str).str.len().max()) if len(series) else 30
    return f"VARCHAR({min(max(max_len + 10, 30), 255)})"


def write_csv_tables(tables: dict[str, pd.DataFrame], output_dir: Path) -> dict[str, int]:
    output_dir.mkdir(parents=True, exist_ok=True)
    counts = {}
    for name, table in tables.items():
        table.to_csv(output_dir / f"{name}.csv", index=False, date_format="%Y-%m-%d", encoding="utf-8")
        counts[name] = len(table)
    return counts


def write_ddl(tables: dict[str, pd.DataFrame], sql_dir: Path) -> Path:
    sql_dir.mkdir(parents=True, exist_ok=True)
    chunks = ["-- Generated by Phoenix HR Insights. SQL Server DDL.\nCREATE SCHEMA phoenix;\nGO\n"]
    for name, table in tables.items():
        columns = []
        for column in table.columns:
            nullable = "NOT NULL" if column.endswith("Key") and column != "ManagerKey" else "NULL"
            columns.append(f"    [{column}] {_sql_type(table[column])} {nullable}")
        primary_key = next((c for c in table.columns if c.endswith("FactKey") or (c.endswith("Key") and c.split("Key")[0].lower() in name.lower())), None)
        if primary_key:
            columns.append(f"    CONSTRAINT [PK_{name}] PRIMARY KEY ([{primary_key}])")
        chunks.append(f"CREATE TABLE phoenix.[{name}] (\n" + ",\n".join(columns) + "\n);\nGO\n")
    path = sql_dir / "create_tables.sql"
    path.write_text("\n".join(chunks), encoding="utf-8")
    return path


def write_run_summary(counts: dict[str, int], output_dir: Path) -> Path:
    path = output_dir / "run_summary.json"
    path.write_text(json.dumps({"tables": counts, "data_classification": "fully synthetic"}, indent=2), encoding="utf-8")
    return path
